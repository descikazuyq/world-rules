// Package world 提供带规则约束的本地世界与命名存档槽。
//
// # 世界与规则
//
// 用 [NewWorld] 建立世界：需要整数地图种子、非空规则版本、地点及其
// 连通关系、角色、物品。时间片从 0 开始。地点与角色标识不得重复，
// 连通关系只能引用已有地点，携带上限不能为负；角色必须位于已有地点，
// 物品数量必须为非负整数且总量不超过其携带上限。初始数据不合法时
// [NewWorld] 返回 *RuleError，不会建立世界。
//
// 用 [World.Apply] 一次原子提交多个移动、物品数量变化和时间推进：
// 移动只能沿规则允许的连通关系，不能引用不存在的角色或物品，不能让
// 数量变负或总量超过上限，时间不能倒退。任意一项违反规则，整次提交
// 失败，世界保持提交前状态。[World.Snapshot] 与 Apply 返回的状态都
// 是深拷贝，修改它们不会影响世界或已保存记录。
//
// # 存档
//
// [Create] 在指定目录建立存档，[Open] 重新打开。Save 首次保存创建
// 命名槽，重名明确拒绝；Replace 覆盖时必须带上此前读到的记录标识，
// 且它仍是该槽最新记录才允许写入。每次成功保存都产生目录内唯一的
// 记录标识，保存完整世界数据、父记录标识和内容校验和（校验和覆盖父
// 记录关系）。同一目录的多个进程或实例并发覆盖同一父记录时，flock
// 与记录标识比较保证只有一个成功，其余收到 *ConflictError。所有写入
// 都先写临时文件再原子改名，崩溃后重开只能看到旧的完整记录或新的
// 完整记录。
//
// [Archive.Branch] 可从某槽的一次历史记录分出新槽，新槽首条记录以它
// 为父并完整复制当时的种子、规则和状态，此后两槽互不影响。覆盖后的
// 历史记录仍可按标识读取。
//
// # 规则检查与升级
//
// [Archive.CheckUpgrade] 传入槽名、可接受的旧版本集合和一份完整目标
// 规则，检查该槽最新存档能否原样承接：角色所在地点仍存在、已列出的
// 物品种类仍被允许（数量为零也算）、携带总量不超过目标上限（目标中
// 没有该角色上限表示不设限）。结果给出所检查的记录标识、旧版本、
// 目标版本、是否兼容及全部有序阻碍；检查只读，不改变世界、历史或槽
// 当前记录。目标规则非法、版本与来源相同（版本名只按相等判断，不按
// 数字大小限制方向）、来源损坏或版本不被接受时报错；槽不存在沿用
// 现有错误。
//
// [Archive.UpgradeRules] 在明确请求时执行升级：入参与检查相同，并带
// 调用方预期的最新记录标识作乐观锁。提交时在写入锁内重新判断当前
// 来源，仍有阻碍返回相同的阻碍信息并拒绝写入，预期标识为空或已过期
// 返回 *ConflictError。成功后追加一条以被升级记录为父的完整新记录，
// 仅替换规则——种子、时间片、角色位置及物品数量和排列原样保留；旧
// 记录保留原规则，已分出的分支不受影响，只接受旧版本的恢复读取仍能
// 找到升级前最近一份可用记录。并发升级或升级与普通覆盖竞争时只有
// 一个成功，其余报告冲突。所有被拒绝的升级都不产生记录、不改变槽
// 当前记录。
//
// 读取（[Archive.Latest]、[Archive.Record]）会检查内容校验和、父记录
// 关系与规则版本。调用方显式给出可接受版本集合；版本不被接受返回
// *VersionRejectedError，且不会替换记录中的规则。最新记录损坏或版本
// 不被接受时，[Archive.RecoverLatest] 可另行读取该槽最近一份校验通过
// 且版本可接受的历史记录；没有这样的记录时返回可用 errors.Is 判断的
// ErrUnrecoverable。读取与恢复读取都不会改写存档。
package world

// Ready 表示基线可以运行。
func Ready() bool { return true }
