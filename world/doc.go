// Package world 提供带规则约束的本地世界与命名存档槽。
//
// # 世界与规则
//
// 用 [NewWorld] 建立世界：需要整数地图种子、非空规则版本、地点及其
// 连通关系、角色、物品。时间片从 0 开始。地点与角色标识不得重复，
// 连通关系只能引用已有地点，携带上限不能为负；角色必须位于已有地点，
// 物品数量必须为非负整数且总量不超过其携带上限。规则版本、地点名称、
// 道路端点、物品种类、携带上限中的角色键，以及角色标识、角色所在地点和
// 所持物品名称都必须是合法 UTF-8——即使该地点或物品暂时无人使用、上限键
// 没有对应的现存角色也一样；含无效字节的字符串保存为 JSON 时会被改写成
// 替换字符“�”，可能使不同标识重名，因此在接纳世界数据时即返回
// *RuleError，不删字节、不换字符、也不自动改名。合法 UTF-8 中真实存在的
// “�”、中文与表情符号都按普通标识接受。初始数据不合法时
// [NewWorld] 返回 *RuleError，不会建立世界。
//
// 也可以用 [GenerateWorld] 按种子生成地图：调用方给出地点列表、必有
// 道路、禁用道路和目标道路总数，以及规则版本、物品种类、携带上限和
// 初始角色。生成的地图是无向道路图，包含全部必有道路、避开全部禁用
// 道路、任意两个地点都能沿道路到达，且不同道路数量严格等于目标值；
// 同一道路重复或反向列出只算一条。同一种子与同一组地图约束的结果完全
// 一致，与输入次序、重复、正反写法、是否生成过其他世界及进程重启无关；
// 规则版本、角色、物品种类与携带上限不影响地图。地点限 1 至 256 个，
// 约束不合法（标识为空、不是合法 UTF-8 或重复、道路引用未知地点或连接自身、同一道路
// 同时必有和禁用、目标数量为负、小于必有道路数、少于连通所需数量、
// 超过可用道路数、禁用道路使地图无法连通）时返回 *RuleError，不产生
// 可用世界；约束有解时每个种子都能成功生成。生成地图的限制不追溯施加
// 到 [NewWorld] 与旧存档；生成的完整地图随存档保存，重新打开、恢复
// 读取和分支都使用记录中的地图，不重新生成。
//
// 用 [World.Apply] 一次原子提交多个移动、物品数量变化和时间推进：
// 移动只能沿规则允许的连通关系，不能引用不存在的角色或物品，不能让
// 最终数量为负或超出 int 范围、真实总量超过上限，时间不能倒退。同一
// 角色同一物品的全部增减与原始数量合并后判断最终结果，精确整数运算
// 不回绕，增减条目次序不影响成败与最终数量。任意一项违反规则，整次
// 提交失败，世界保持提交前状态。[World.Snapshot] 与 Apply 返回的状态
// 都是深拷贝，修改它们不会影响世界或已保存的记录。
//
// # 存档
//
// [Create] 在指定目录建立存档，[Open] 重新打开。Save 首次保存创建
// 命名槽，重名明确拒绝；Replace 覆盖时必须带上此前读到的记录标识，
// 且它仍是该槽最新记录才允许写入。每次成功保存都产生目录内唯一的
// 记录标识，保存完整世界数据、父记录标识和内容校验和（校验和覆盖父
// 记录关系）。同一目录的多个进程或实例并发覆盖同一父记录时，flock
// 与记录标识比较保证只有一个成功，其余收到 *ConflictError。所有写入
// 都先写临时文件再原子改名，崩溃后重开只能看到旧的完整记录或新的
// 完整记录。
//
// [Archive.Branch] 可从某槽的一次历史记录分出新槽，新槽首条记录以它
// 为父并完整复制当时的种子、规则和状态，此后两槽互不影响。覆盖后的
// 历史记录仍可按标识读取。
//
// 槽指针除指向当前最新记录外，还内嵌一份按“保存生效次序”排列的历史
// 索引（最新在前）。该索引只在记录文件完整落盘、保存完整生效后才随
// 指针原子更新，因此残留临时文件、写完但未完成保存的孤儿记录，以及
// CAS 竞争失败的写入都不会出现在索引中。旧版本写出的裸指针（无历史
// 索引）仍可直接打开和读取：读取时在内存中沿校验通过的父链回退重建，
// 不要求用户转换数据；该槽第一次成功覆盖或升级后，重建出的原有历史与
// 新记录会一并持久化，旧历史从此获得完整恢复能力。读取与恢复读取本身
// 都不改写目录内容。
//
// 读取（[Archive.Latest]、[Archive.Record]）会检查文本编码、同一对象内的
// 名称唯一性、内容校验和、父记录关系、世界状态与规则版本；对完整状态的
// 认可与 [WorldFromState] 重建世界一致，时间片为负的记录属于损坏记录
// （校验和匹配、版本被接受都不能使其合法），按 *CorruptError 拒绝。同一
// 对象内名称出现第二次的记录也属于损坏记录：encoding/json 会用后值静默
// 覆盖前值，解析结果可能校验和匹配、世界合法，记录里却同时写着相互矛盾
// 的两份内容。名称按 JSON 转义还原后的字符串判断，直接写出的名称与同一
// 名称的 Unicode 转义视为同名；不同对象（如两个物品条目各自的数量字段）
// 各自独立，不受影响。文本编码损坏与名称重复都先于格式版本与规则版本
// 判断，即使规则版本不被接受也报损坏而不报版本拒绝。调用方显式给出可
// 接受版本集合；版本不被接受返回 *VersionRejectedError，且不会替换记录中
// 的规则。最新记录损坏、
// 被删除、被截断成无法解析的内容，或连同若干中间记录一起损坏/版本不被
// 接受时，
// [Archive.RecoverLatest] 依据历史索引按保存次序（与文件修改时间和世界
// 时间片大小无关）回溯，返回该槽最近一份校验通过且版本可接受的已保存
// 记录；它不会因为损坏文件里读不出父标识而提前放弃，也不信任其中被
// 篡改的父标识或槽首标记，因此恢复既不会被引向别的槽，也不会遮住本槽
// 更早的可用记录。分支槽只在分支自身成功保存的记录中查找，即使分支
// 首条记录损坏也不越过分支边界，其他槽即使种子和规则相同也不替代。
// 分支全无可用记录、或没有任何版本可接受的完好记录时，返回可用
// errors.Is 判断的 ErrUnrecoverable；槽不存在仍报不存在，槽指针不可读
// 仍报损坏。读取与恢复读取都不会改写存档。
//
// # 浏览已保存的历史
//
// 除了按已知标识读取，还可以先用 [Archive.History] 浏览一个槽已经保存
// 生效的全部历史，再从列表里挑一份旧记录，用 [Archive.Record] 按其标识
// 读取当时的完整世界。History 不需要可接受版本参数，返回每条记录的
// [RecordInfo]：记录标识 ID、父标识 Parent、槽首标记 SlotFirst 与规则
// 版本 Version；元信息不含完整世界，读世界仍要走 Record。
//
// 列表按“保存生效的先后”排列，最近保存的在最前，槽首记录在末尾；它不
// 按世界时间片大小排序，也不按记录文件修改时间排序。确认恢复后新记录
// 允许指向较早的来源（时间片可以回到来源时刻），该新记录仍排在最前，
// 原先已经生效的其他保存按原次序保留。父标识与列表次序是两件事：父标识
// 只说明这条记录承接自哪一次保存。
//
// 不要把槽首标记统一解释成父标识为空：只有直接建立的槽首记录没有父
// 记录；分支槽的首条记录虽标记为槽首，却以来源槽记录为父记录。分支槽
// 只列分支自身保存生效的记录，即使分支首记录的父指向来源槽，也不会把
// 来源槽的历史列进来。
//
// 列表中的记录能否立即使用，要区分完整性与规则版本：History 只做与
// Record 一致的完整性检查（文本编码完好、同一对象内无重复名称、格式受
// 支持、内容与父关系校验通过、世界状态合法、直接父记录文件存在），不
// 筛选规则版本，完好但版本较旧或陌生的记录仍会列出。用 Record 读取时
// 必须显式给出可接受版本集合，版本不被接受会得到 *VersionRejectedError，
// 那不是历史列表出错。
//
// 带历史索引的槽中，损坏、缺失或无法解析的记录会被略过，其余合格记录
// 继续列出；同一对象内名称重复的记录也按损坏略过，不影响其余记录的次序；某条记录的直接父文件被删除时，它也因父关系不成立被略过，
// 而父文件仍在、仅内容损坏时，不因此略过自身完好的子记录。没有历史
// 索引的旧格式槽只沿校验通过的父链列出能确认归属本槽的记录，在损坏处
// 停止，不承诺越过损坏继续寻找更老记录。槽存在但没有合格记录时返回
// 成功的空列表；槽不存在报 *NotFoundError，槽指针无法解析报
// *CorruptError，三者不能混为一谈。History 与 Record 都是只读操作：
// 不切换槽当前记录、不修补或删除记录，也不替换世界规则。
//
// # 预览恢复与确认恢复
//
// [Archive.RecoverLatest] 只回答“能恢复到哪份记录”，不改变槽当前指向。
// 需要正式恢复时先用 [Archive.PreviewRecovery] 预览：传入槽名与可接受
// 规则版本集合，返回槽当前指向的记录标识、按本槽保存生效次序选中的来源
// 记录标识，以及来源记录的完整世界状态（深拷贝）。选择规则与恢复读取
// 相同——最近一份内容与父关系校验通过且版本可接受的记录，越过缺失、截断、
// 校验失败与版本不被接受的记录，分支只用自己的历史；槽当前记录本就完好
// 且版本可接受时可以选它本身。槽不存在报不存在，槽指针无法解析报损坏
// （仍会返回其当前标识，即使该记录已损坏或被删除），没有可用记录返回
// ErrUnrecoverable。预览绝不写入、修补或删除任何数据，可重复调用。
//
// [Archive.ConfirmRecovery] 依据预览结果正式恢复：传入槽名、预览中的当前
// 记录标识与来源记录标识，以及可接受版本集合。任一标识为空，或槽已不再
// 指向该当前记录（被并发覆盖、升级或另一次确认抢先提交），都返回现有的
// *ConflictError；当前标识只与槽所指记录比较，即使它已损坏或被删除，也
// 不妨碍从本槽完好旧记录恢复。确认在排他锁下重新读取并完整校验来源，不
// 使用调用方可能修改过的预览状态：来源必须仍属于该槽、仍通过内容与父
// 关系校验且版本可接受；其他槽的记录与未生效的残留/孤儿记录按不存在
// 拒绝，来源后来被删除、损坏或版本不被接受时分别返回已有的不存在、损坏
// 或版本拒绝错误，不改选其他来源。
//
// 成功确认后产生一条独立的新记录（即使来源就是当前记录）：槽指向新记录，
// 父记录是选中的来源，种子、完整规则、时间片、角色及物品的内容和排列均
// 原样复制，允许时间片回到来源时刻。旧历史按原保存次序保留，新记录排在
// 最前；来源之后仍完好的旧记录可照常读取或分支，已存在的分支不受影响。
// 同一当前标识上的并发确认、以及确认与普通覆盖或规则升级竞争时，flock
// 与标识比较保证最多一个成功。重新打开存档后可以读新记录并继续提交、
// 覆盖或升级；旧格式存档沿用已有的历史归属限制，第一次成功确认后重建出
// 的旧历史与新记录一并持久化。写入中断后重开，槽只能保持确认前的指向和
// 历史，或同时看到新记录与更新后的历史；尚未生效的新记录不会进入恢复
// 候选，也不能作为来源。
//
// # 规则升级
//
// [Archive.CheckUpgrade] 检查槽当前最新记录能否在目标规则下继续使用：
// 传入槽名、可接受的旧版本集合与目标规则，返回所检查的记录标识、旧版本、
// 目标版本、是否兼容及具体阻碍。检查只读取来源记录并计算兼容性，不改变
// 世界、历史或槽当前记录。目标规则须先满足规则自身的合法性要求，且版本
// 与来源记录不同（版本只按相等判断，不按数字大小限制升级）。兼容只判断
// 能否原样承接当前角色状态：每个角色所在地点仍存在，已列出的物品种类仍被
// 允许（数量为零也算），各角色携带总量不超过目标上限（按真实总量精确判断，
// 不回绕；真实总量超出 int 范围时阻碍以完整十进制给出）；目标中没有该角色
// 上限时表示不设上限。允许删去无人所在的地点、不再出现的物品种类或旧
// 连通关系，也允许增加内容。多个阻碍一次返回全部，同类问题按角色标识、
// 物品标识排序，重复检查输出顺序一致。
//
// [Archive.Upgrade] 在检查通过后用目标规则生成一条新记录：传入与检查
// 相同的条件，并带调用方预期的最新记录标识。提交时在排他锁下重新判断
// 当前来源，仍有阻碍则返回相同的阻碍信息并拒绝写入；预期标识为空或已
// 不是该槽最新记录时返回现有冲突错误。被拒绝的升级不增加历史记录，也不
// 改变槽当前记录。成功后槽增加一条完整的新记录，以被升级记录为父，保存
// 目标规则；种子、时间片、角色位置及物品数量和排列保持原样。并发升级或
// 升级与普通覆盖竞争时，只有预期标识与最新记录一致的一个成功，其余收到
// 冲突。旧记录继续保留原规则，已经分出的分支不受影响；重新打开存档后能
// 读取新记录并继续提交，只接受旧版本的恢复读取仍能找到升级前最近一份
// 可用记录。写入中断后，槽只能指向升级前或升级后的完整记录。普通读取
// 不会自动升级；调用方修改检查结果、目标规则或读回的状态，不应影响已
// 保存的数据。
//
// # 显式迁移旧存档
//
// 升级只能原样承接角色状态。需要在地点或物品改名、合并后仍保留角色继续
// 使用新规则时，用 [Archive.PreviewMigration] 与 [Archive.Migrate] 显式
// 迁移：传入槽名、可接受的旧版本集合、目标规则，以及旧地点到新地点、
// 旧物品到新物品的对应关系。目标规则须合法且版本与来源不同；每个对应
// 关系的来源必须存在于旧规则、目标必须存在于新规则（即使暂时没有角色
// 使用也要检查），空目标或未知名称返回规则错误。未指定的名称保持原样，
// 所有转换只作用于原始名称一次，不沿对应关系连续替换，因此互换名称也有
// 确定结果。
//
// 角色按对应关系改变所在地点（无需符合旧道路），物品改变种类但不增减
// 数量；多个条目转换成同一种物品时合并数量，按原列表中首次出现的位置
// 保留一个条目，零数量仍保留并参与种类检查。种子、时间片、角色标识及
// 角色排列保持不变。合并数量或携带总量超出 int 范围时返回规则错误，不
// 回绕也不丢弃物品。
//
// [Archive.PreviewMigration] 先给出预览：返回来源记录标识、旧新版本、
// 转换后的完整状态及是否可提交。转换后仍有缺失地点、不被允许的物品或
// 超过目标携带上限时，一次列出全部阻碍，注明角色和相关名称或数量，重复
// 预览顺序一致。预览不改动存档，修改返回状态也不影响来源。来源缺失、
// 损坏或版本不被接受时沿用已有对应错误，不自动挑选历史记录。
//
// [Archive.Migrate] 正式迁移：需带预览的来源标识，并重新提交目标规则与
// 对应关系；提交时在排他锁下重新读取和计算，不直接保存调用方改过的预览
// 状态。来源标识为空或槽已更新时返回冲突；仍有阻碍时返回阻碍并拒绝
// 保存。成功生成以来源为父的新记录，保存目标规则与转换后的状态，加入
// 本槽保存次序。与覆盖、升级、确认恢复或另一次迁移竞争时，同一来源最多
// 一个成功。任何拒绝都不改变当前记录或历史；中断后重新打开只能看到迁移
// 前或迁移后的完整记录与历史。旧记录及已有分支保留原状态，恢复读取仍能
// 找到旧版本；迁移后的记录可继续按新规则移动、改变物品并保存，普通读取
// 不自动转换。
package world

// Ready 表示基线可以运行。
func Ready() bool { return true }
